/**
 * T151 stage 2 — all-family frozen V5 pure plan geometry.
 *
 * A faithful port of the frozen generator's `plans()` / `applicability()` /
 * `noteState()` / `noteAt()` for the 14 active families
 * (`grammars.js` `basePlans` + `expansion.js` `plans`, freeze
 * `43a8d54e…85a16`). It does NOT touch the sealed expression schema, the
 * renderer, `StyleRegistry`, crop solving or the stage-1 candidate provider;
 * it produces task-local algorithm DTOs that are adapted to the T154 expression
 * model at integration.
 *
 * Ordering, per-family branch generation and the expansion second-variant sets
 * mirror the reference exactly; the differential test compares every rectangle
 * against a fixture generated by running the unmodified frozen runtime
 * (`tasks/T151/evidence/ref_plans.js`).
 *
 * Text metrics are injected through [TextMeasurer]; [LINE_HEIGHT_STUB] is the
 * T153 `textMetricModelled` line-height document model. Browser-faithful note
 * measurement stays an explicit residual.
 */
object FrozenGrammarPlans {

