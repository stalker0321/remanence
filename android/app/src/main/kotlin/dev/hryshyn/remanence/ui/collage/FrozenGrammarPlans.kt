    private fun noteAt(
        d: Input,
        x: Double,
        y: Double,
        w: Double,
        size: Double,
        font: String,
        maxShort: Int,
        measure: TextMeasurer,
    ): Note? {
        val text = d.note ?: return null
        var m = measure.measure(text, w, size, Math.ceil(size * 1.12), font)
        var state = "short"
        if (m.lines > maxShort) {
            m = measure.measure(text, w, 16.0, 20.0, font)
            state = if (m.lines > 10) "long" else "medium"
        }
        return Note(Rect(x, y, w, m.height), state)
    }

    private fun sound(d: Input, r: Rect, mode: String): Music? {
        val music = d.music ?: return null
        val resolved = if (music.artwork) mode else if (mode == "sleeve") "sleeve-empty" else mode
        return Music(r, resolved)
    }

    private data class Closing(val note: Note?, val music: Music?, val end: Double)

    private fun closing(d: Input, g: GrammarDef, n: NoteState, end: Double, x: Double, w: Double, mh: Double): Closing {
        val note = if (n.height > 0.0) Note(Rect(x, end - n.height, n.width, n.height), n.state) else null
        var top = if (note != null) note.rect.y - 10.0 else end
        val music = if (d.music != null) {
            Music(Rect(x, top - mh, w, mh), if (d.music.artwork && g.artwork != "ignored") "thumbnail" else "text")
        } else null
        if (music != null) top = music.rect.y - 8.0
        return Closing(note, music, top)
    }

    private fun bands(
        p: List<Photo>,
        recipe: List<Int>,
        r: Rect,
        gap: Double = 5.0,
        weights: List<Double>? = null,
        power: Double = 0.0,
        shape: String = "rect",
        zooms: List<Double> = listOf(1.0),
    ): List<Tile> {
        var pos = 0
        var y = r.y
        val heights = weights ?: recipe.map { 1.0 }
        val sum = heights.sum()
        val out = ArrayList<Tile>()
        for (k in recipe.indices) {
            val count = recipe[k]
            val group = p.subList(pos, pos + count)
            val h = (r.h - gap * (recipe.size - 1)) * heights[k] / sum
            val ws = group.map { Math.pow(clamp(it.width / it.height, 0.45, 2.0), power) }
            val wSum = ws.sum()
            var x = r.x
            for (j in group.indices) {
                val w = (r.w - gap * (count - 1)) * ws[j] / wSum
                out += tile(group[j], Rect(x, y, w, h), shape, zooms)
                x += w + gap
            }
            y += h + gap
            pos += count
        }
        return out
    }

    private fun tile(p: Photo, r: Rect, shape: String = "rect", zooms: List<Double> = listOf(1.0), assignmentRole: String? = null): Tile =
        Tile(p.id, r, shape, zooms, assignmentRole)

    private fun brand(rect: Rect, size: Double, font: String = "StudySans", orientation: String = "horizontal", weight: Int = 400, align: String = "left"): Mark =
        Mark("Remanence", rect, size, orientation, align, false, weight, font)

    private fun sender(d: Input, rect: Rect, size: Double, font: String = "StudySans", orientation: String = "horizontal", italic: Boolean = false, weight: Int = 400, align: String = "left"): Mark =
        Mark("sender", rect, size, orientation, align, italic, weight, font)

    private fun recipes(n: Int): List<List<Int>> = when (n) {
        3 -> listOf(listOf(1, 2), listOf(2, 1))
        4 -> listOf(listOf(1, 1, 2), listOf(2, 2))
        else -> listOf(listOf(1, 2, 2), listOf(2, 3), listOf(3, 2))
    }

    private fun recs(n: Int): List<Int> = when (n) {
        1 -> listOf(1)
        2 -> listOf(2)
        3 -> listOf(1, 2)
        4 -> listOf(2, 2)
        else -> listOf(2, 3)
    }

    private fun partRecipe(len: Int, stacked: Boolean): List<Int> = when {
        len == 3 -> listOf(1, 2)
        stacked && len == 2 -> listOf(1, 1)
        else -> listOf(len)
    }

    private fun clamp(n: Double, a: Double, b: Double): Double = Math.max(a, Math.min(b, n))

    private fun num(v: Double): String {
        if (v.isFinite() && v == Math.floor(v) && Math.abs(v) < 1e15) return v.toLong().toString()
        return v.toString()
    }
