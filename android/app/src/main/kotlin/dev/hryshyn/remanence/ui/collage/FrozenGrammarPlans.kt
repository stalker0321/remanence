    fun applicability(d: Input, g: GrammarDef): Motion {
        val reasons = ArrayList<String>()
        if (g.id == 22 && d.photos.none { it.hasProminentFace }) {
            reasons += "A prominent detected human anchor is required"
        }
        if (d.photos.size !in g.counts) {
            reasons += "Supports ${g.counts.joinToString(" / ")} photos; input has ${d.photos.size}"
        }
        if (g.music == "required" && d.music == null) {
            reasons += "Music required: it is a structural part of this grammar"
        }
        if (g.music == "unsupported" && d.music != null) {
            reasons += "Music unsupported: this grammar is intentionally silent"
        }
        if (g.note == "required" && d.note == null) {
            reasons += "A note is required to organise this composition"
        }
        if (g.artwork == "required" && d.music?.artwork != true) {
            reasons += "Music artwork required for the sleeve"
        }
        return Motion(reasons.isEmpty(), reasons)
    }

    fun noteState(d: Input, g: GrammarDef, measure: TextMeasurer): NoteState {
        val text = d.note ?: return NoteState(0.0, 0.0, "absent", "")
        val width = when (g.id) {
            21 -> 140.0
            18 -> 290.0
            6 -> 300.0
            20 -> 300.0
            else -> 328.0
        }
        val font = when {
            g.id == 5 || g.id == 21 -> "StudySerif"
            g.id == 12 -> "StudyMono"
            else -> "StudySans"
        }
        val size = when {
            g.id == 5 || g.id == 21 -> 27.0
            g.id == 12 -> 17.0
            else -> 23.0
        }
        val m = measure.measure(text, width, size, Math.ceil(size * 1.1), font)
        if (m.lines <= 3 && m.height <= 90) return NoteState(width, m.height, "short", text)
        val regular = measure.measure(text, width, 16.0, 20.0, font)
        return NoteState(width, regular.height, "regular", text)
    }

    fun plans(d: Input, g: GrammarDef, n: NoteState, measure: TextMeasurer): List<Plan> {
        val out = ArrayList<Plan>()
        if (g.id < 22 && g.id != 21 && g.id != 20) {
            out += basePlans(d, g, n)
        }
        when (g.id) {
            6 -> {
                addMusicTransitionSpines(d, g, n, measure, out)
                return out.takeLast(2) + out.dropLast(2)
            }
            20 -> addSleeveBridge(d, g, measure, out)
            21 -> return plansLetterMargin(d, g, n, measure, out)
            22 -> addFirstLight(d, g, measure, out)
            23 -> addOpenWindows(d, g, measure, out)
            24 -> addPulse(d, g, measure, out)
            25 -> addOffsetPrints(d, g, measure, out)
            26 -> addRibbon(d, g, measure, out)
            27 -> addMonument(d, g, measure, out)
        }
        return out
    }

    // ----------------------------------------------------- assignment + policy

    data class Assignment(val feasible: Boolean, val readingOrder: List<String>)

    /**
     * Frozen `assignPhotos(..., {lockOrder:true})` structural outcome without the
     * crop solver: tiles map 1:1 to the source order and the branch is infeasible
     * if any tile falls below the frozen readability floor (84 px short side /
     * 9,500 px area). Crop-safety and face/object role feasibility are re-checked
     * by the solver at integration, not here.
     */
    fun sourceOrderAssignment(plan: Plan): Assignment {
        val below = plan.tiles.any {
            Math.min(it.rect.w, it.rect.h) < 84.0 || it.rect.w * it.rect.h < 9500.0
        }
        if (below) return Assignment(false, emptyList())
        return Assignment(true, plan.tiles.map { it.photoId })
    }

    data class Branch(val grammarId: Int, val plan: Plan)

    /**
     * Frozen product selection policy (`DECISIONS.md`): grammar-first, at most
     * two geometrically distinct layouts per grammar and up to twelve
     * expressions total, in enumeration order. This is the stated selection
     * policy, not a function in the runtime code.
     */
    fun selectExpressions(branches: List<Branch>, maxPerFamily: Int = 2, maxTotal: Int = 12): List<Branch> {
        val perFamily = HashMap<Int, MutableSet<String>>()
        val selected = ArrayList<Branch>()
        for (branch in branches) {
            if (selected.size >= maxTotal) break
            val seen = perFamily.getOrPut(branch.grammarId) { HashSet() }
            if (seen.size >= maxPerFamily) continue
            if (seen.add(geometryKey(branch.plan))) selected += branch
        }
        return selected
    }

    private fun geometryKey(plan: Plan): String =
        plan.tiles.joinToString(";") {
            listOf(num(it.rect.x), num(it.rect.y), num(it.rect.w), num(it.rect.h), it.shape).joinToString(",")
        }

    // --------------------------------------------------------------- base plans

    private fun basePlans(d: Input, g: GrammarDef, n: NoteState): List<Plan> = when (g.id) {
        5 -> baseEditorial(d, g, n)
        6 -> baseMusicTransition(d, n)
        11 -> baseInterlock(d, g, n)
        12 -> baseStrips(d, g, n)
        17 -> baseMass(d, n)
        18 -> baseMount(d, g, n)
        21 -> baseLetterOpening(d, n)
        else -> emptyList()
    }

    private fun baseEditorial(d: Input, g: GrammarDef, n: NoteState): List<Plan> {
        val p = d.photos
        val r0 = closing(d, g, n, 603.0, 16.0, 328.0, 48.0)
        val prov = listOf(
            brand(Rect(12.0, 4.0, 340.0, 75.0), 64.0, "StudySerif"),
            sender(d, Rect(16.0, 613.0, 328.0, 23.0), 20.0, "StudySerif", italic = true, align = "right"),
        )
        val r = Rect(10.0, 101.0, 340.0, r0.end - 101.0)
        val out = ArrayList<Plan>()
        for (rec in recipes(p.size)) {
            for (power in listOf(0.0, 1.0)) {
                val weightSets = listOf(
                    rec.mapIndexed { i, _ -> if (i == 0) 1.3 else 1.0 },
                    rec.map { 1.0 },
                    rec.mapIndexed { i, _ -> if (i == 0) 0.45 else 1.0 },
                )
                for (weights in weightSets) {
                    out += Plan(
                        "editorial-${rec.joinToString("+")}-${if (power != 0.0) "proportional" else "equal"}-${num(weights[0])}",
                        bands(p, rec, r, gap = 5.0, weights = weights, power = power, zooms = listOf(1.05, 1.0)),
                        r0.note, r0.music, prov, emptyList(),
                    )
                }
            }
        }
        return out
    }

    private fun baseMusicTransition(d: Input, n: NoteState): List<Plan> {
        val p = d.photos
        val N = p.size
        val note = if (n.height > 0.0) Note(Rect(40.0, 628.0 - n.height, 300.0, n.height), n.state) else null
        val end = if (note != null) note.rect.y - 12.0 else 634.0
        val out = ArrayList<Plan>()
        val splits = when (N) {
            3 -> listOf(1, 2)
            4 -> listOf(2)
            else -> listOf(2, 3)
        }
        for (split in splits) {
            for (frac in listOf(0.52, 0.43, 0.60, 0.28)) {
                for (power in listOf(0.0, 1.0)) {
                    for (stacked in listOf(false, true)) {
                        val h1 = (end - 82.0) * frac
                        val h2 = end - 82.0 - h1
                        val music = Music(
                            Rect(32.0, h1 + 4.0, 328.0, 54.0),
                            if (d.music?.artwork == true) "thumbnail" else "text",
                        )
                        val prov = listOf(
                            brand(Rect(3.0, 8.0, 24.0, 612.0), 22.0, "Narrow", "vertical-up", weight = 700),
                            sender(d, Rect(42.0, h1 + 60.0, 304.0, 18.0), 14.0, "StudySans"),
                        )
                        val a = p.subList(0, split)
                        val b = p.subList(split, p.size)
                        val ra = partRecipe(a.size, stacked)
                        val rb = partRecipe(b.size, stacked)
                        out += Plan(
                            "hinge-$split+${N - split}-${num(frac)}-${if (power != 0.0) "ratio" else "equal"}-${if (stacked) "stacked" else "paired"}",
                            bands(a, ra, Rect(32.0, 0.0, 328.0, h1), gap = 4.0, power = power, zooms = listOf(1.04, 1.0)) +
                                bands(b, rb, Rect(32.0, h1 + 82.0, 328.0, h2), gap = 4.0, power = power, zooms = listOf(1.04, 1.0)),
                            note, music, prov, emptyList(),
                        )
                    }
                }
            }
        }
        return out
    }

    private fun baseInterlock(d: Input, g: GrammarDef, n: NoteState): List<Plan> {
        val p = d.photos
        val N = p.size
        val note = if (n.height > 0.0) Note(Rect(16.0, 608.0 - n.height, 328.0, n.height), n.state) else null
        val end = if (note != null) note.rect.y - 12.0 else 610.0
        val out = ArrayList<Plan>()
        for (frac in listOf(0.57, 0.46, 0.65, 0.34)) {
            for (power in listOf(0.55, 1.0)) {
                for (stacked in listOf(false, true)) {
                    val upperCount = N - 2
                    val uh = (end - 69.0) * frac
                    val by = uh + 69.0
                    val bh = end - by
                    val music = Music(
                        Rect(250.0, by, 104.0, bh),
                        if (d.music?.artwork == true) "tile-art" else "tile-text",
                    )
                    val prov = listOf(
                        brand(Rect(10.0, uh + 11.0, 340.0, 49.0), 46.0, "Gothic"),
                        sender(d, Rect(16.0, 615.0, 328.0, 20.0), 16.0, "Gothic", align = "right"),
                    )
                    val upperRecipe = if (stacked && upperCount == 2) listOf(1, 1) else listOf(upperCount)
                    out += Plan(
                        "interlock-$upperCount/2+music-${num(frac)}-${num(power)}-${if (stacked) "stacked" else "paired"}",
                        bands(p.subList(0, upperCount), upperRecipe, Rect(6.0, 4.0, 348.0, uh), power = power, shape = "round", gap = 7.0, zooms = listOf(1.04, 1.0)) +
                            bands(p.subList(N - 2, N), listOf(2), Rect(6.0, by, 237.0, bh), power = power, shape = "round", gap = 7.0, zooms = listOf(1.04, 1.0)),
                        note, music, prov, emptyList(),
                    )
                }
            }
        }
        return out
    }

    private fun baseStrips(d: Input, g: GrammarDef, n: NoteState): List<Plan> {
        val p = d.photos
        val N = p.size
        val r0 = closing(d, g, n, 602.0, 28.0, 322.0, 44.0)
        val r = Rect(28.0, 0.0, 332.0, r0.end)
        val prov = listOf(
            brand(Rect(2.0, 8.0, 23.0, 570.0), 18.0, "StudyMono", "vertical-down"),
            sender(d, Rect(28.0, 615.0, 316.0, 20.0), 15.0, "StudyMono", align = "right"),
        )
        val out = ArrayList<Plan>()
        for (mode in listOf("equal", "weighted")) {
            val ws = p.map { Math.min(1.0 / (it.width / it.height), 1.0 / 1.65) }
            val sum = ws.sum()
            var y = 0.0
            val tiles = p.mapIndexed { i, ph ->
                val h = Math.min(
                    332.0 / 1.65,
                    if (mode == "equal") (r.h - 4.0 * (N - 1)) / N else (r.h - 4.0 * (N - 1)) * ws[i] / sum,
                )
                val t = tile(ph, Rect(28.0, y, 332.0, h), "rect", listOf(1.0))
                y += h + 4.0
                t
            }
            out += Plan("score-$N-$mode", tiles, r0.note, r0.music, prov, emptyList())
        }
        return out
    }

    private fun baseMass(d: Input, n: NoteState): List<Plan> {
        val p = d.photos
        val N = p.size
        val r0 = closing(d, def(17), n, 532.0, 16.0, 328.0, 44.0)
        val prov = listOf(
            sender(d, Rect(10.0, 543.0, 340.0, 19.0), 15.0, "StudySans", align = "right"),
            brand(Rect(6.0, 565.0, 350.0, 75.0), 72.0, "Narrow", weight = 700),
        )
        val r = Rect(0.0, 0.0, 360.0, r0.end)
        val recs = when (N) {
            3 -> listOf(listOf(1, 2), listOf(2, 1))
            4 -> listOf(listOf(2, 2), listOf(1, 3))
            else -> listOf(listOf(2, 3), listOf(3, 2))
        }
        val out = ArrayList<Plan>()
        for (rec in recs) {
            for (weights in listOf(listOf(1.2, 1.0), listOf(0.85, 1.0), listOf(0.40, 1.0))) {
                for (power in listOf(0.0, 0.8)) {
                    out += Plan(
                        "mass-${rec.joinToString("+")}-${num(weights[0])}-${num(power)}",
                        bands(p, rec, r, weights = weights, power = power, gap = 2.0, zooms = listOf(1.08, 1.0)),
                        r0.note, r0.music, prov, emptyList(),
                    )
                }
            }
        }
        return out
    }

