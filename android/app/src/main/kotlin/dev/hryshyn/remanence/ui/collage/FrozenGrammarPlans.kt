    private fun addMusicTransitionSpines(
        d: Input,
        g: GrammarDef,
        n: NoteState,
        measure: TextMeasurer,
        out: MutableList<Plan>,
    ) {
        val p = d.photos
        val N = p.size
        val note = noteAt(d, 16.0, 0.0, 328.0, 24.0, "StudySans", 3, measure)
        val bottom = if (note != null) 612.0 - note.rect.h else 615.0
        if (note != null) note.rect.y = bottom + 3.0
        for (frac in listOf(0.52, 0.43)) {
            val leftCount = Math.ceil(N / 2.0).toInt()
            val rightCount = N - leftCount
            val music = Music(Rect(156.0, 0.0, 48.0, bottom - 24.0), "spine")
            val a = bands(p.subList(0, leftCount), List(leftCount) { 1 }, Rect(0.0, 0.0, 153.0, bottom - 24.0), gap = 5.0, zooms = listOf(1.08, 1.0))
            val b = bands(p.subList(leftCount, N), List(rightCount) { 1 }, Rect(207.0, 0.0, 153.0, bottom - 24.0), gap = 5.0, zooms = listOf(1.08, 1.0))
            out += Plan(
                "sound-spine-$leftCount/$rightCount-${num(frac)}",
                a + b, note, music,
                listOf(
                    sender(d, Rect(12.0, bottom - 20.0, 330.0, 21.0), 18.0, "StudySerif", italic = true),
                    brand(Rect(12.0, 618.0, 330.0, 19.0), 17.0, "StudySans", align = "right"),
                ),
                emptyList(),
            )
        }
    }

    private fun addSleeveBridge(d: Input, g: GrammarDef, measure: TextMeasurer, out: MutableList<Plan>) {
        val p = d.photos
        val N = p.size
        for (sleeveH in listOf(145.0, 126.0)) {
            val note = noteAt(d, 15.0, 0.0, 330.0, 25.0, "StudySerif", 3, measure)
            val end = if (note != null) 606.0 - note.rect.h else 606.0
            if (note != null) note.rect.y = end
            val music = sound(d, Rect(14.0, end - sleeveH - 9.0, 332.0, sleeveH), "sleeve")
                ?: continue
            val ph = music.rect.y - 38.0
            val recs = when (N) {
                3 -> listOf(listOf(1, 2), listOf(2, 1))
                4 -> listOf(listOf(2, 2), listOf(1, 1, 2))
                else -> listOf(listOf(2, 3), listOf(1, 2, 2))
            }
            for (rec in recs) {
                out += Plan(
                    "sleeve-bridge-${rec.joinToString("+")}-${num(sleeveH)}",
                    bands(p, rec, Rect(0.0, 0.0, 360.0, ph), gap = 4.0, power = 0.5, zooms = listOf(1.1, 1.03, 1.0)),
                    note, music,
                    listOf(
                        sender(d, Rect(14.0, ph + 5.0, 330.0, 28.0), 23.0, "StudySerif", italic = true),
                        brand(Rect(15.0, 617.0, 330.0, 20.0), 18.0, "StudySans", align = "right"),
                    ),
                    emptyList(),
                )
            }
        }
    }

    private fun plansLetterMargin(
        d: Input,
        g: GrammarDef,
        n: NoteState,
        measure: TextMeasurer,
        out: MutableList<Plan>,
    ): List<Plan> {
        val p = d.photos
        val N = p.size
        val full = noteAt(d, 18.0, 0.0, 324.0, 29.0, "StudySerif", 3, measure)
        if (full != null) {
            for (topH in listOf(240.0, 290.0, 340.0)) {
                val sy = topH + 14.0
                val ny = sy + 36.0
                val music = if (d.music != null) Music(Rect(18.0, 586.0, 324.0, 47.0), "inline") else null
                val note = Note(Rect(full.rect.x, ny, full.rect.w, full.rect.h), full.state)
                val end = if (music != null) 580.0 else 611.0
                if (note.rect.y + note.rect.h <= end) {
                    val rec = when (N) {
                        3 -> listOf(1, 2)
                        4 -> listOf(2, 2)
                        else -> listOf(2, 3)
                    }
                    out += Plan(
